PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS departamento (
 id TEXT PRIMARY KEY NOT NULL, nombre TEXT NOT NULL UNIQUE COLLATE NOCASE,
 gerente TEXT UNIQUE REFERENCES empleado(id));
CREATE TABLE IF NOT EXISTS persona (
 id TEXT PRIMARY KEY NOT NULL, nombre TEXT NOT NULL, correo TEXT NOT NULL UNIQUE COLLATE NOCASE,
 direccion BLOB NOT NULL, telefono BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS empleado (
 id TEXT PRIMARY KEY NOT NULL REFERENCES persona(id), inicio TEXT NOT NULL, sueldo BLOB NOT NULL,
 departamento TEXT REFERENCES departamento(id) ON DELETE SET NULL,
 activo INTEGER NOT NULL DEFAULT 1 CHECK(activo IN (0,1)));
CREATE TABLE IF NOT EXISTS proyecto (
 id TEXT PRIMARY KEY NOT NULL, nombre TEXT NOT NULL UNIQUE COLLATE NOCASE, descripcion TEXT NOT NULL,
 inicio TEXT NOT NULL, estado TEXT NOT NULL CHECK(estado IN ('PLANIFICADO','ACTIVO','PAUSADO','FINALIZADO')));
CREATE TABLE IF NOT EXISTS asignacion (
 id INTEGER PRIMARY KEY, empleado TEXT NOT NULL REFERENCES empleado(id), proyecto TEXT NOT NULL REFERENCES proyecto(id),
 rol TEXT NOT NULL, inicio TEXT NOT NULL, fin TEXT CHECK(fin IS NULL OR fin>=inicio));
CREATE UNIQUE INDEX IF NOT EXISTS asignacion_activa ON asignacion(empleado,proyecto) WHERE fin IS NULL;
CREATE TABLE IF NOT EXISTS registro (
 id INTEGER PRIMARY KEY, asignacion INTEGER NOT NULL REFERENCES asignacion(id), fecha TEXT NOT NULL,
 minutos INTEGER NOT NULL CHECK(minutos BETWEEN 1 AND 1440), descripcion TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS usuarios (
 nombre TEXT PRIMARY KEY COLLATE NOCASE, hash TEXT NOT NULL, rol TEXT NOT NULL CHECK(rol IN ('admin','consulta')));
CREATE TABLE IF NOT EXISTS cache_api (clave TEXT PRIMARY KEY, obtenido_en TEXT NOT NULL, datos TEXT NOT NULL);
